<h2>6. 信息安全保障措施</h2>
<ul>
    <li>网站与控制面板全程强制采用高强度 TLS 传输加密，免费自动化部署并无缝续签 SSL 证书。</li>
    <li>所有账户密码均采用行业标准不可逆算法进行高强度加盐哈希（Hash）存储，严禁明文记录。</li>
    <li>运维管理员访问严格实行 SSH 密钥认证与多因素双重身份认证（2FA），全面禁用弱密码。</li>
    <li>各租户主机账户在 Linux 内核与操作系统层面严格隔离，从底层防止跨目录访问。</li>
    <li>系统部署主机防火墙、ModSecurity Web 应用防火墙（WAF）以及持续恶意代码查杀引擎。</li>
    <li>核心数据库每日执行受保护的高可用冷备，存储于高安全权限隔离目录。</li>
</ul>
<p>一旦发生影响您个人数据的安全事件，我们承诺在<strong>72 小时</strong>内向监管机构报告，并在合理可行的时间内迅速告知受影响的个人。</p>

