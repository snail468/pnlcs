<p>本《服务等级协议》（以下简称“本协议”或 SLA）规定了本公司向付费主机客户承诺的网络与基础设施可用性指标，以及在未能达到指标时的补偿机制。本协议作为<a href="{{ route('legal.show', 'terms') }}">《服务条款》</a>不可分割的组成部分。</p>

<h2>1. 服务可用性承诺</h2>
<p>针对所有商业付费主机方案，我们承诺在每个自然月内达到<strong>99.9% 的网络与服务器基础设施可用性</strong>。这对应于每个自然月中非计划内的停机时间不超过约<strong>43 分钟</strong>。</p>
<p>该承诺范围专指物理主机节点、宿主机操作系统、网络交换路由及本公司提供的基础运行环境之连通性。客户自身编写的代码报错、数据库慢查询、第三方程序死锁或配置不当导致的站点不可访问，不属于本承诺范畴。</p>

<h2>2. 不计入不可用时间的除外情形</h2>
<p>在计算每月可用性时，下列情形不作为停机时间统计：</p>
<ul>
    <li><strong>预先通知的计划停机维护：</strong>至少提前 72 小时通过邮件发出维护预告，通常安排在业务低峰期（如当地时间凌晨 02:00 至 06:00）进行，且单月累计计划维护时间不超过 4 小时；</li>
    <li><strong>紧急高危安全漏洞修补：</strong>当发生零日（0-day）漏洞遭受在野利用等危及集群安全的极端情况时，为防止数据失窃所必须采取的紧急加固，事后会立即补发公告；</li>
    <li>由客户站点自身应用程序、WordPress 核心或第三方插件自身的代码缺陷、逻辑死循环导致的崩溃；</li>
    <li>超出您当前主机方案的 CPU、物理内存或磁盘 I/O 硬件配额导致的响应缓慢或 503 错误；</li>
    <li>因违反<a href="{{ route('legal.show', 'aup') }}">《可接受使用政策》</a>或逾期未缴费导致的合法挂起与封禁；</li>
    <li>域名解析 DNS 配置错误、域名过期未续费或域名被注册局锁死引发的访问中断；</li>
    <li>本公司管辖机房之外的骨干互联网光缆故障、跨国网络路由震荡或客户本地宽带营运商故障；</li>
    <li>不可抗力事件：包括自然灾害、战争、全民罢工、大范围公用电网断电或政府主管机构的法定阻断禁令。</li>
</ul>

