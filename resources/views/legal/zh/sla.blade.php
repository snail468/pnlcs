<p>SLA 补偿并非系统自动扣减，需由客户提交核验申请。请在发生停机事件所在月份结束后的<strong>30 天</strong>内，在客户中心提交工单并列明受影响的日期、时间段及监测日志。我们将在<strong>10 个工作日</strong>内将您的申报与官方系统监控历史交叉比对并作出审批认定。</p>
