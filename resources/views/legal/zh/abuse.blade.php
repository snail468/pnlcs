<h2>1. 举报材料应包含的基本要素</h2>
<p>为使我们能够迅速定点排查，您的举报应尽可能详尽，并包含以下关键要素：</p>
<ul>
    <li><strong>精确的网址链接（URL）：</strong>必须提供涉嫌侵权或违规页面的完整直接链接（如 <code>https://example.com/bad-path</code>），而不能仅提供一级域名或笼统说明；</li>
    <li><strong>举报的具体违规类型：</strong>明确指出属于侵犯著作权、网络钓鱼诈骗、恶意木马分发、垃圾邮件源头、名誉诽谤还是其他违法情形；</li>
    <li><strong>事实简要陈述：</strong>清晰、客观地阐述判定该内容违法的具体事实与理由；</li>
    <li><strong>举报人身份与联系方式：</strong>您的真实姓名、联系邮箱、所属机构或被授权人身份证明；</li>
    <li><strong>确凿的辅助证据材料：</strong>违规网页截图、完整邮件头原文（针对 SPAM 垃圾邮件必须提供 RFC 822 完整邮件标头）、抓包日志或对比证明文件。</li>
</ul>
<p>我们也依法接收匿名举报，但若举报材料严重缺失且无法联系您补充核实，因证据不足调查可能会受到限制。</p>

<h2>2. 知识产权与版权侵权投诉（DMCA 与等效程序）</h2>
<p>如果您是合法版权所有人或经正式授权的代理人，提交侵权下架通知（Take-Down Notice）时应包含以下声明：</p>
<ul>
    <li>对主张享有合法著作权的作品名称及原版权归属链接的详细描述；</li>
    <li>明确表明您是合法著作权所有人，或已获得法定权利人正式合法授权的真实声明；</li>
    <li>本着诚实信用原则，确认所投诉之材料未经版权所有人、其代理人或法律允许授权使用的善意陈述；</li>
    <li>保证所提供信息真实准确的保证，以及您的实体亲笔签名或受法律认可的电子签名。</li>
</ul>
<p>上述要求严格符合美国《数字千年版权法》（DMCA 17 U.S.C. §512(c)(3)）以及土耳其第 5846 号《知识与艺术作品法》附加第 4 条之法定规范。</p>

<h3>被投诉方的反通知（Counter-Notice）程序</h3>
<p>若您的网站内容因版权投诉被依法下架，而您确信该投诉系出于事实误认或恶意举报，您有权依法提交反通知：载明被下架内容的精确定位、您诚实确信移除系误判的法律与事实理由、您的真实身份及接受争议管辖的承诺。我们将在收到合规反通知后依法转送至投诉方。若投诉方在 <strong>10 个工作日</strong> 内未能出具已依法向司法机关正式立案起诉的凭据，我们将在期满后恢复下架内容。</p>
<p>请注意：无论是投诉方还是被投诉方，蓄意提供虚假陈述或伪造证据均须承担由此引发的严重法律民事赔偿责任。</p>

